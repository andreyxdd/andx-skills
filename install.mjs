#!/usr/bin/env node
// Symlink canonical andx skills into the shared ~/.agents/skills (Cursor, Codex, Kimi, Pi, Gemini, ...) and
// ~/.claude/skills (Claude Code reads only its own); agents and hooks per harness.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const HELP = `Usage: node install.mjs [--home DIR] [--worktree-backend native|auto|wt] [--uninstall-hooks]
  Links the andx skills into ~/.agents/skills and ~/.claude/skills (and removes the links older installs
  made in ~/.cursor/skills and ~/.codex/skills, which Cursor would list twice), links the agents into
  ~/.claude/agents (Cursor reads it too) and, when installed, ~/.kimi-code/agents, writes Codex agents as
  ~/.codex/agents/*.toml, and registers the hooks. --home DIR stands in for ~ (also for the git config below).
  --worktree-backend X  also sets git config --global andx.worktreeBackend X (what worktree.mjs uses to
                        create run worktrees; see its --help) and prints it
  --uninstall-hooks     removes only the hooks`;
const ROOT = path.dirname(fileURLToPath(import.meta.url));
const SKILLS = [
  "andx-init",
  "andx-plan",
  "andx-schedule",
  "andx-execute",
  "andx-orchestration",
  "andx-debug-and-fix",
  "andx-deploy",
  "andx-deploy-init",
  "andx-execute-and-deploy",
  "andx-execute-and-review",
  "andx-execute-review-and-deploy",
  "andx-mr-review",
  "andx-mr-babysit",
  "andx-mr-create",
  "andx-security-review",
  "andx-listen-start",
  "andx-listen-end",
];
const RETIRED = ["andx-pr-review"];
const SKILL_HOMES = [".agents", ".claude"];
const LEGACY_HOMES = [".cursor", ".codex"];
// Agents that run a mid-tier model instead of inheriting the parent's: home dir -> model id for that harness.
const MODELS = { "andx-spec-reviewer.md": { ".claude": "sonnet", ".cursor": "claude-sonnet-5-5" } };

// Replace `dest` with a link to `target`. Windows: directory junctions (no admin); a file symlink
// may need Developer Mode, so fall back to a copy. Returns "linked" or "copied".
export function link(target, dest) {
  fs.rmSync(dest, { recursive: true, force: true });
  if (process.platform !== "win32") fs.symlinkSync(target, dest);
  else if (fs.statSync(target).isDirectory()) fs.symlinkSync(target, dest, "junction");
  else {
    try {
      fs.symlinkSync(target, dest, "file");
    } catch (e) {
      if (e.code !== "EPERM") throw e;
      fs.copyFileSync(target, dest);
      return "copied";
    }
  }
  return "linked";
}

// True when `p` is a link (or Windows junction) into this repo, i.e. one an install made.
const ownLink = (p) => {
  try {
    return fs.lstatSync(p).isSymbolicLink() && path.resolve(path.dirname(p), fs.readlinkSync(p)).startsWith(ROOT + path.sep);
  } catch {
    return false;
  }
};

// Codex agents are TOML. JSON strings are valid TOML basic strings.
export function codexAgent(md, name) {
  const [, fm = "", body = md] = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(md) ?? [];
  const field = (k) => {
    const v = fm.match(new RegExp(`^${k}:[ \\t]*(.*?)\\s*$`, "m"))?.[1] ?? "";
    return v.startsWith('"') ? JSON.parse(v) : v;
  };
  return `# Generated by andx-skills install.mjs from agents/${name}.md; re-run install after edits.\n` +
    `name = ${JSON.stringify(field("name") || name)}\ndescription = ${JSON.stringify(field("description"))}\n` +
    `developer_instructions = ${JSON.stringify(body.trim())}\n`;
}

function main(args) {
  if (args.includes("--help") || args.includes("-h")) return console.log(HELP) ?? 0;
  const i = args.indexOf("--home");
  const home = i >= 0 && args[i + 1] ? path.resolve(args[i + 1]) : os.homedir();
  const b = args.indexOf("--worktree-backend");
  const backend = b >= 0 ? args[b + 1] : undefined;
  if (b >= 0 && !["native", "auto", "wt"].includes(backend)) {
    console.error(`--worktree-backend must be native, auto or wt\n\n${HELP}`);
    return 2;
  }
  const script = (name, ...a) => spawnSync(process.execPath, [path.join(ROOT, "scripts", name), ...a], { stdio: "inherit" }).status;

  if (args.includes("--uninstall-hooks")) return script("install-hooks.mjs", "uninstall", "--home", home) ?? 1;
  if (script("check-skills.mjs", ROOT) !== 0) {
    console.error("check-skills failed; nothing linked");
    return 1;
  }

  for (const h of SKILL_HOMES) {
    const target = path.join(home, h, "skills");
    fs.mkdirSync(target, { recursive: true });
    for (const skill of SKILLS) {
      const src = path.join(ROOT, skill);
      if (!fs.existsSync(src)) {
        console.error(`missing canonical skill: ${src}`);
        return 1;
      }
      link(src, path.join(target, skill));
      console.log(`linked ${path.join(target, skill)} -> ${src}`);
    }
    for (const skill of RETIRED) fs.rmSync(path.join(target, skill), { recursive: true, force: true });
  }
  for (const h of LEGACY_HOMES) {
    for (const skill of [...SKILLS, ...RETIRED]) {
      const p = path.join(home, h, "skills", skill);
      if (!ownLink(p)) continue;
      fs.rmSync(p, { recursive: true, force: true });
      console.log(`removed old link ${p} (now read from ~/.agents/skills)`);
    }
  }

  // Agents link into ~/.claude/agents, which Cursor reads too, and ~/.kimi-code/agents when Kimi is installed
  // (Kimi ignores model). MODELS agents are written as copies with a per-harness model instead; Cursor prefers
  // the ~/.cursor/agents copy over the same-name Claude one. Codex gets generated TOML.
  const agentDirs = [".claude", ...(fs.existsSync(path.join(home, ".kimi-code")) ? [".kimi-code"] : [])].map((h) => path.join(home, h, "agents"));
  const codex = fs.existsSync(path.join(home, ".codex")) ? path.join(home, ".codex", "agents") : null;
  for (const d of [...agentDirs, codex].filter(Boolean)) fs.mkdirSync(d, { recursive: true });
  for (const name of fs.readdirSync(path.join(ROOT, "agents")).filter((f) => f.endsWith(".md")).sort()) {
    const src = path.join(ROOT, "agents", name);
    if (codex) {
      const dest = path.join(codex, `${path.basename(name, ".md")}.toml`);
      fs.rmSync(dest, { force: true });
      fs.writeFileSync(dest, codexAgent(fs.readFileSync(src, "utf8"), path.basename(name, ".md")));
      console.log(`wrote ${dest} (re-run after edits)`);
    }
    for (const agents of agentDirs.slice(MODELS[name] ? 1 : 0)) {
      const how = link(src, path.join(agents, name));
      console.log(`${how} ${path.join(agents, name)}${how === "copied" ? " (symlink not permitted; re-run after edits)" : ""}`);
    }
    if (!MODELS[name]) continue;
    for (const [h, model] of Object.entries(MODELS[name])) {
      const dest = path.join(home, h, "agents", name);
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.rmSync(dest, { force: true }); // an old symlink would route the write into the repo source
      fs.writeFileSync(dest, fs.readFileSync(src, "utf8").replace(/^model: inherit$/m, `model: ${model}`));
      console.log(`wrote ${dest} (model: ${model}; re-run after edits)`);
    }
  }

  const status = script("install-hooks.mjs", "install", "--home", home);
  if (status !== 0) return status ?? 1;
  if (backend) {
    const env = { ...process.env };
    if (i >= 0) {
      Object.assign(env, { HOME: home, USERPROFILE: home });
      delete env.GIT_CONFIG_GLOBAL;
    }
    const r = spawnSync("git", ["config", "--global", "andx.worktreeBackend", backend], { env, encoding: "utf8" });
    if (r.status !== 0) {
      console.error(`${r.stderr}git config --global andx.worktreeBackend ${backend} failed`);
      return 1;
    }
    console.log(`worktree backend: git config --global andx.worktreeBackend = ${backend}`);
  }
  console.log(`Done. Canonical source: ${ROOT}`);
  console.log("Run node install-companions.mjs for optional companions (e.g. react-best-practices).");
  return 0;
}

if (import.meta.main) process.exitCode = main(process.argv.slice(2));
